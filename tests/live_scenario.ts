// Live Helium scenario, TS side (#1600 gate 1-2 live). Only touches tabs it opens itself.
import * as h from "../helpers";
const out: any[] = [];
const rec = async (label: string, fn: () => any) => { try { const v = await fn(); out.push([label, v === undefined ? null : v]); } catch (e: any) { out.push([label, "ERR:" + e.message]); } };
const PAGE = "data:text/html,<title>t1600</title><input id=q><button id=b onclick=\"document.title='clicked'\" style='position:fixed;left:0;top:0;width:200px;height:60px'>b</button><div style='height:3000px'></div>";
const tid = await h.new_tab(PAGE);
await rec("wait_for_load", () => h.wait_for_load());
await rec("page_info", async () => { const p = await h.page_info(); return Object.fromEntries(Object.entries(p).filter(([k]) => ["url", "title", "ph"].includes(k))); });
await rec("tab listed", async () => (await h.list_tabs()).some((t) => t.targetId === tid));
await rec("current_tab is mine", async () => (await h.current_tab()).targetId === tid);
await rec("js", () => h.js("1+1"));
await rec("js float", () => h.js("1.5*2"));
await rec("js unicode", () => h.js("'é🟢'"));
await rec("click", async () => { await h.click(100, 30); await h.wait(0.3); return h.js("document.title"); });
await rec("type", async () => { await h.js("document.getElementById('q').focus()"); await h.type_text("héllo"); return h.js("document.getElementById('q').value"); });
await rec("press_key", async () => { await h.press_key("Backspace"); await h.press_key("Z"); return h.js("document.getElementById('q').value"); });
await rec("dispatch_key", async () => { await h.js("window.k='';document.getElementById('q').addEventListener('keydown',e=>window.k=e.key)"); await h.dispatch_key("#q", "Enter", "keydown"); return h.js("window.k"); });
await rec("scroll", async () => { await h.scroll(100, 300, 500); await h.wait(0.5); return h.js("scrollY > 0"); });
await rec("screenshot", async () => Buffer.from(await Bun.file(await h.screenshot("/tmp/t1600-live-ts.png")).arrayBuffer()).subarray(0, 8).toString("hex"));
await rec("dialog", async () => { await h.js("setTimeout(()=>confirm('sure?'),50)"); await h.wait(0.5); return (await h.page_info()).dialog?.message ?? null; });
await rec("dialog closed", async () => { await h.cdp("Page.handleJavaScriptDialog", { accept: true }); await h.wait(0.3); return "dialog" in (await h.page_info()); });
await rec("goto", async () => { await h.goto("data:text/html,<title>two</title>"); await h.wait_for_load(); return h.js("document.title"); });
await rec("cdp error", () => h.cdp("Nope.x"));
await rec("upload missing", () => h.upload_file("#missing", "/tmp/x"));
await rec("events", async () => (await h.drain_events()).map((e: any) => e.method).includes("Page.loadEventFired"));
await h.close_tab(tid); await h.wait(0.5);
await rec("closed", async () => (await h.list_tabs()).some((t) => t.targetId === tid));
await rec("temp_tab", () => h.temp_tab("data:text/html,<title>tmp</title>", async () => { await h.wait_for_load(); return h.js("document.title"); }));
console.log(JSON.stringify(out));
process.exit(0);
